import assert from 'node:assert/strict';
import {FULL_RUN_ORDER,runOrder,nextStep,validateSourceSnapshot,submissionAction,applyAcceptance,assertRepairAttempt} from './lib/notebook-contract.mjs';
const s={ledger:{fingerprint:'FP'},notebook:{url:'https://notebook.test/new',sourcePolicy:{courseGroups:['课程']},includedOptionalQuestions:['Q7B','Q12B'],completedQuestions:[],manualBlock:{status:'BLOCKED',stepId:'Q0'}},caseId:'NEW'};
const snap={url:s.notebook.url,verifiedAt:'now',checks:[{label:'课程',checked:true},{label:'选择“NEW-FP”',checked:true},{label:'选择“OLD”',checked:false}]};
assert.equal(validateSourceSnapshot(snap,s),snap);
assert.throws(()=>validateSourceSnapshot({...snap,checks:snap.checks.map(c=>({...c,checked:true}))},s));
assert.throws(()=>validateSourceSnapshot({...snap,checks:[]},s));
assert.throws(()=>validateSourceSnapshot({...snap,checks:snap.checks.map(c=>({...c,checked:c.label==='课程'?false:c.checked}))},s));
assert.throws(()=>validateSourceSnapshot({...snap,url:'old'},s));
assert.equal(submissionAction(null,false),'SUBMIT');
assert.throws(()=>submissionAction({confirmedAt:null},true));
assert.throws(()=>submissionAction({confirmedAt:'t'},true));
assert.throws(()=>submissionAction({confirmedAt:'t',sourceSnapshot:snap},false));
assert.equal(submissionAction({confirmedAt:'t',sourceSnapshot:snap},true),'RECOVER');
assertRepairAttempt('REPAIR-Q1-ARGUMENT-V1',[],null);
assertRepairAttempt('REPAIR-Q1-ARGUMENT-V2',['REPAIR-Q1-ARGUMENT-V1-receipt.json'],null);
assert.throws(()=>assertRepairAttempt('REPAIR-Q1-ARGUMENT-V3',[],null));
assertRepairAttempt('REPAIR-Q6-FORMAT-V3',['REPAIR-Q6-FORMAT-V1-receipt.json','REPAIR-Q6-FORMAT-V2-receipt.json'],null,false);
assert.throws(()=>assertRepairAttempt('REPAIR-Q1-ARGUMENT-V2',['REPAIR-Q1-ARGUMENT-V1-receipt.json','REPAIR-Q1-ARGUMENT-V2-receipt.json'],null));
assertRepairAttempt('REPAIR-Q1-ARGUMENT-V2',['REPAIR-Q1-ARGUMENT-V1-receipt.json','REPAIR-Q1-ARGUMENT-V2-receipt.json'],{confirmedAt:'t'});
assert.deepEqual(runOrder(s),FULL_RUN_ORDER);assert.equal(FULL_RUN_ORDER.length,19);
const review={stepId:'Q0',status:'PASS',rationale:'Checked facts and sources',effectiveAnswer:'v2.txt',auditPath:'audit.json',version:'v2',sourceReceipt:'receipt.json',receipt:{confirmedAt:'t',sourceSnapshot:snap}};
assert.throws(()=>applyAcceptance(s,{...review,stepId:'Q1'},{status:'PASS'},{}));
assert.throws(()=>applyAcceptance(s,review,{status:'BLOCKED'},{}));
const approved=applyAcceptance(s,review,{status:'PASS'},{effectiveAnswer:'hash'});
assert.equal(approved.notebook.manualBlock,null);assert.equal(nextStep(approved),'Q1');
assert.equal(approved.notebook.reviewHistory[0].previousBlock.status,'BLOCKED');
assert.equal(approved.notebook.manualApprovals.Q0.effectiveAnswer,'v2.txt');
assert.equal(s.notebook.manualBlock.status,'BLOCKED');
assert.equal(nextStep({...s,notebook:{...s.notebook,completedQuestions:FULL_RUN_ORDER.slice(0,4)}}),'CP-A-M');
assert.equal(nextStep({...s,notebook:{...s.notebook,completedQuestions:FULL_RUN_ORDER.slice(0,18)}}),'CP-D-M');
console.log('Source reset/unknown, receipts, version release and 19-step order regressions passed.');
